"""
Generates the Tomb Door's textures (block/tomb_door_bottom, _top) and models: block/tomb_door_slab
(the stone slab, 2 blocks tall, drawn by TombDoorRenderer and used by the item), block/tomb_door_empty
(what the blockstate shows: nothing but a particle texture, since the renderer draws the slab
whether shut, open or moving) and item/tomb_door (the slab, shrunk to fit a slot).

THE METHOD
----------
A carved stone slab on vanilla's smooth_stone, drawn as one 16x32 face so no block line crosses its
middle: smooth_stone's border round the outside only, a sunken border two pixels in from the edge
running round the whole slab, and a carved cross in the upper half. No ring pull (it slides).
Carving is a groove: its shaded top/left edge darker, its lit bottom/right
edge a shade brighter than the stone, the way vanilla's chiseled blocks show depth.

The slab is 4px thick, centred in the block (z 6..10 in the north-facing model), so it stands on the
wall's middle plane; TombDoorBlock's shape matches it. Open, the renderer slides it 14px sideways,
into the wall beside the doorway.

Run from the repo root; it overwrites what it writes, so never hand-edit those files:
    python tools/gen_tomb_door.py
"""
import io
import json
import os
import zipfile

from PIL import Image

TEX = "src/main/resources/assets/dungeonblocks/textures/block/"
MODEL = "src/main/resources/assets/dungeonblocks/models/"
VANILLA_JAR = os.path.expanduser("~/.gradle/caches/forge_gradle/minecraft_repo/versions/1.20.1/client-extra.jar")



def vanilla(name):
    with zipfile.ZipFile(VANILLA_JAR) as jar:
        return Image.open(io.BytesIO(jar.read(f"assets/minecraft/textures/block/{name}.png"))).convert("RGBA")


def shade(c, f):
    return tuple(max(0, min(255, round(v * f))) for v in c[:3]) + (255,)


def face():
    """The whole 16x32 face, row 0 at the top, as ONE slab: smooth_stone's 1px border runs round the
    outside of the two blocks only, never across the middle, and the inside is smooth_stone's own
    interior, the lower block's mirrored so the speckle does not repeat."""
    stone = vanilla("smooth_stone")
    inner = stone.crop((1, 1, 15, 15))
    im = Image.new("RGBA", (16, 32))
    im.paste(inner, (1, 1))
    im.paste(inner.transpose(Image.FLIP_TOP_BOTTOM), (1, 15))
    im.paste(inner.crop((0, 0, 14, 2)), (1, 29))
    px = im.load()
    sp = stone.load()
    for x in range(16):
        px[x, 0] = sp[x, 0]
        px[x, 31] = sp[x, 15]
    for y in range(1, 31):
        px[0, y] = sp[0, 1 + (y - 1) % 14]
        px[15, y] = sp[15, 1 + (y - 1) % 14]

    def groove(cells):
        """Carve the given pixels: darken them, then light the edge below/right of each run."""
        cells = set(cells)
        for x, y in cells:
            px[x, y] = shade(px[x, y], 0.62)
        for x, y in cells:
            for dx, dy in ((1, 0), (0, 1)):
                n = (x + dx, y + dy)
                if n not in cells and 0 <= n[0] < 16 and 0 <= n[1] < 32:
                    px[n] = shade(px[n], 1.12)

    border = [(x, y) for y in range(2, 30) for x in (2, 13)] + [(x, y) for x in range(2, 14) for y in (2, 29)]
    groove(border)
    cross = [(x, 6) for x in range(5, 11)] + [(x, 7) for x in range(5, 11)]         + [(x, y) for y in range(4, 14) for x in (7, 8)]
    groove(cross)
    # no ring pull: the slab slides, it does not swing, so there is nothing to pull
    return im


def edge():
    """The slab's thin sides, top and bottom: smooth_stone's interior with no border at all, so the
    sides show no line where the two blocks meet (smooth_stone itself draws one at every block edge).
    The interior's 14 rows and columns, then its first two again, fill the 16."""
    inner = vanilla("smooth_stone").crop((1, 1, 15, 15)).load()
    im = Image.new("RGBA", (16, 16))
    for y in range(16):
        for x in range(16):
            im.putpixel((x, y), inner[x % 14, y % 14])
    return im


def slab_model():
    def faces(tex, y):
        f = {"north": {"uv": [0, 0, 16, 16], "texture": tex}, "south": {"uv": [16, 0, 0, 16], "texture": tex},
             "east": {"uv": [6, 0, 10, 16], "texture": "#side"}, "west": {"uv": [6, 0, 10, 16], "texture": "#side"}}
        f["down" if y == 0 else "up"] = {"uv": [0, 6, 16, 10], "texture": "#side"}
        return f
    return {
        "__comment": "Generated by tools/gen_tomb_door.py; do not hand-edit.",
        "parent": "block/block",
        "textures": {"bottom": "dungeonblocks:block/tomb_door_bottom", "top": "dungeonblocks:block/tomb_door_top",
                     "side": "dungeonblocks:block/tomb_door_edge", "particle": "minecraft:block/smooth_stone"},
        "elements": [{"name": "lower", "from": [0, 0, 6], "to": [16, 16, 10], "faces": faces("#bottom", 0)},
                     {"name": "upper", "from": [0, 16, 6], "to": [16, 32, 10], "faces": faces("#top", 1)}],
        "display": {
            "gui": {"rotation": [30, 225, 0], "translation": [0, -3, 0], "scale": [0.42, 0.42, 0.42]},
            "ground": {"rotation": [0, 0, 0], "translation": [0, 3, 0], "scale": [0.18, 0.18, 0.18]},
            "fixed": {"rotation": [0, 0, 0], "translation": [0, -3, 0], "scale": [0.42, 0.42, 0.42]},
            "thirdperson_righthand": {"rotation": [75, 45, 0], "translation": [0, 2.5, 0], "scale": [0.2, 0.2, 0.2]},
            "firstperson_righthand": {"rotation": [0, 45, 0], "translation": [0, 0, 0], "scale": [0.22, 0.22, 0.22]},
            "firstperson_lefthand": {"rotation": [0, 225, 0], "translation": [0, 0, 0], "scale": [0.22, 0.22, 0.22]}}}


def main():
    whole = face()
    edge().save(TEX + "tomb_door_edge.png")
    whole.crop((0, 0, 16, 16)).save(TEX + "tomb_door_top.png")
    whole.crop((0, 16, 16, 32)).save(TEX + "tomb_door_bottom.png")
    models = {
        "block/tomb_door_slab": slab_model(),
        "block/tomb_door_empty": {"__comment": "Generated by tools/gen_tomb_door.py: the renderer draws the slab.",
                                  "textures": {"particle": "minecraft:block/smooth_stone"}},
        "item/tomb_door": {"parent": "dungeonblocks:block/tomb_door_slab"},
    }
    for name, model in models.items():
        with open(MODEL + name + ".json", "w", newline="\n") as f:
            json.dump(model, f, indent=2)
    print("wrote tomb_door textures and models")


if __name__ == "__main__":
    main()
